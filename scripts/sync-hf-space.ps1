# Mirrors the deployable AI service into hf-space-publish (the Hugging Face Space repo).
#
# Sources of truth:
#   miqorai-ai-service/                 app/, model/, examples/, requirements*.txt, README.md, .env.example
#   deploy/docker/ai-service.Dockerfile the one AI image recipe
#
# The central Dockerfile builds with the REPOSITORY ROOT as context, so its COPY
# sources start with "miqorai-ai-service/". The Space builds with hf-space-publish/
# as context, so the generated hf-space-publish/Dockerfile has that prefix removed
# from every COPY line. Everything else is identical.
#
# Edit the sources and rerun this script; never edit hf-space-publish by hand.
# hf-space-publish/.git and .gitattributes (Space deploy metadata) are left untouched.
$ErrorActionPreference = "Stop"

$repoRoot = Split-Path -Parent $PSScriptRoot
$source = Join-Path $repoRoot "miqorai-ai-service"
$target = Join-Path $repoRoot "hf-space-publish"
$dockerfileSource = Join-Path $repoRoot "deploy/docker/ai-service.Dockerfile"

foreach ($required in @($source, $target, $dockerfileSource)) {
    if (-not (Test-Path $required)) { throw "Not found: $required" }
}

$directories = @("app", "examples")
if (Test-Path (Join-Path $source "model")) { $directories += "model" }

foreach ($dir in $directories) {
    $from = Join-Path $source $dir
    $to = Join-Path $target $dir
    if (Test-Path $to) { Remove-Item -Recurse -Force $to }
    Copy-Item -Recurse -Force $from $to
    # Drop local interpreter artifacts from the deploy copy.
    Get-ChildItem -Path $to -Recurse -Directory -Filter "__pycache__" |
        Remove-Item -Recurse -Force
}

$files = @("README.md", ".env.example") +
    @(Get-ChildItem -Path $source -File -Filter "requirements*.txt" | ForEach-Object { $_.Name })

foreach ($file in $files) {
    $from = Join-Path $source $file
    if (Test-Path $from) {
        Copy-Item -Force $from (Join-Path $target $file)
    }
}

# Generate hf-space-publish/Dockerfile for the Space's build context.
$banner = @(
    "# GENERATED by scripts/sync-hf-space.ps1 from deploy/docker/ai-service.Dockerfile - do not edit.",
    "# Build context: hf-space-publish/ (COPY sources have the miqorai-ai-service/ prefix removed).",
    ""
)
$lines = Get-Content -Path $dockerfileSource | ForEach-Object {
    if ($_ -match '^\s*COPY\s') { $_ -replace 'miqorai-ai-service/', '' } else { $_ }
}
$dockerfileTarget = Join-Path $target "Dockerfile"
# LF line endings: the Space builds on Linux.
[System.IO.File]::WriteAllText($dockerfileTarget, (($banner + $lines) -join "`n") + "`n")

# The Space needs no .dockerignore (every COPY names an explicit path); remove a stale one.
$staleIgnore = Join-Path $target ".dockerignore"
if (Test-Path $staleIgnore) { Remove-Item -Force $staleIgnore }

Write-Host "Synced miqorai-ai-service -> hf-space-publish ($($directories -join ', '); $($files -join ', '); Dockerfile generated)"
